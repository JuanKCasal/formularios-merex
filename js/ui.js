let toastTimer;
export function toast(msg, ms = 2400) {
  const t = document.getElementById('toast');
  t.textContent = msg;
  t.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => t.classList.remove('show'), ms);
}

/** Ventana de confirmación propia (evita los diálogos del navegador). */
export function confirmBox({ title, text = '', ok = 'Aceptar', cancel = 'Cancelar', danger = false }) {
  return new Promise((resolve) => {
    const root = document.getElementById('modal-root');
    root.innerHTML = `
      <div class="modal-back">
        <div class="modal" role="dialog" aria-modal="true" aria-labelledby="mt">
          <h3 id="mt">${title}</h3>
          ${text ? `<p>${text}</p>` : ''}
          <div class="modal-actions">
            <button class="btn ghost" data-r="0">${cancel}</button>
            <button class="btn ${danger ? 'danger' : 'primary'}" data-r="1">${ok}</button>
          </div>
        </div>
      </div>`;
    const close = (v) => { root.innerHTML = ''; resolve(v); };
    root.querySelector('.modal-back').addEventListener('click', (e) => {
      const b = e.target.closest('[data-r]');
      if (b) close(b.dataset.r === '1');
      else if (e.target.classList.contains('modal-back')) close(false);
    });
    root.querySelector('[data-r="1"]').focus();
  });
}
